export function humanize(slug) {
  return slug
    .split("-")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");
}

export function altText(item) {
  const titles = [item.title, item.titleZh].filter(Boolean);
  return titles.length ? titles.join(" / ") : humanize(item.slug);
}

export function captionText(item) {
  return [item.description, item.descriptionZh].filter(Boolean).join(" ");
}
